// Memoized: only recomputes when `todos` or `filter` change.
export const selectFilteredTodos = createSelector(
  [selectTodos, selectTodosFilter],
  (todos, filter) =>
    filter === "all" ? todos : todos.filter((todo) => todo.status === filter),
);

